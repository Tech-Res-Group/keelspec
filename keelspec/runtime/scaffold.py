"""``keelspec tools scaffold TOOL-x``: an MCP server skeleton from a tool artifact.

The artifact's operations become the server's tools: same names, the operation's
``description`` as the docstring, and a typed argument list from its
``input_schema`` when it has one. Each body raises ``NotImplementedError`` until
someone writes it. A generated test asserts that the server's ``list_tools()``
matches the artifact, which is the offline half of PAC-073.

Generated code imports ``MCPServer`` (mcp 2.x) and falls back to ``FastMCP``
(mcp 1.x). It never imports KeelSpec: a tool server is a product, not a test fixture
of this tool. Pure string generation; nothing here needs the SDK.
"""
from __future__ import annotations

import keyword
import pathlib
import re

from ..agents import operations

PY_TYPES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool",
            "object": "dict", "array": "list"}


def slug(tool_id: str) -> str:
    """``TOOL-payments-ledger`` -> ``payments_ledger``: the package under servers/."""
    name = re.sub(r"[^0-9a-zA-Z]+", "_", tool_id.removeprefix("TOOL-")).strip("_").lower()
    if not name or name[0].isdigit() or keyword.iskeyword(name):
        name = f"tool_{name}"
    return name


def _params(schema: dict | None) -> str:
    props = (schema or {}).get("properties") or {}
    required = set((schema or {}).get("required") or [])
    out = []
    for name in sorted(props, key=lambda n: (n not in required, list(props).index(n))):
        if not name.isidentifier() or keyword.iskeyword(name):
            continue
        spec = props[name] if isinstance(props[name], dict) else {}
        py = PY_TYPES.get(spec.get("type"), "object")
        out.append(f"{name}: {py}" if name in required else f"{name}: {py} | None = None")
    return ", ".join(out)


def _docstring(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def render_server(tool: dict) -> str:
    funcs = []
    for name, op in operations(tool).items():
        doc = op.get("description") or f"{tool.get('title') or tool['id']}: {name}."
        se = op.get("side_effects") or "unknown"
        funcs.append(f'''

@server.tool()
def {name}({_params(op.get("input_schema"))}) -> dict:
    """{_docstring(doc)}

    Side effects: {se}.
    """
    raise NotImplementedError("{tool['id']}.{name} is not written yet")''')
    title = _docstring(tool.get("title") or tool["id"])
    return f'''"""MCP server for {tool['id']}: {title}.

Generated by `keelspec tools scaffold {tool['id']}`. The tool names must stay equal to
the artifact's operations (PAC-073); test_server.py checks that.
"""
from __future__ import annotations

try:
    from mcp.server.mcpserver import MCPServer
    from mcp.server.mcpserver.exceptions import ToolError
except ImportError:  # mcp 1.x
    from mcp.server.fastmcp import FastMCP as MCPServer
    from mcp.server.fastmcp.exceptions import ToolError

# Raise ToolError for a failure you expect (bad id, not found): the caller gets your
# message. Any other exception is reported as a crash.
__all__ = ["ToolError", "server"]

server = MCPServer("{tool['id']}")
{chr(10).join(funcs)}


if __name__ == "__main__":
    server.run()
'''


def render_main(tool: dict) -> str:
    return f'''"""`python -m servers.{slug(tool["id"])}` runs the {tool["id"]} server on stdio."""
from .server import server

server.run()
'''


def render_test(tool: dict) -> str:
    declared = sorted(operations(tool))
    return f'''"""The server exposes exactly the operations {tool["id"]} declares (PAC-073)."""
import asyncio

import pytest

pytest.importorskip("mcp")

from servers.{slug(tool["id"])}.server import server  # noqa: E402

DECLARED = {declared!r}


def test_tools_match_the_artifact():
    tools = asyncio.run(server.list_tools())
    assert sorted(t.name for t in tools) == DECLARED
'''


def scaffold(tool: dict, root: str | pathlib.Path, out_dir: str = "servers",
             force: bool = False) -> list[pathlib.Path]:
    """Write the skeleton under ``<root>/<out_dir>/<slug>/``. Refuses to overwrite
    existing files unless ``force``; returns the files written."""
    base = pathlib.Path(root) / out_dir
    pkg = base / slug(tool["id"])
    files = {
        pkg / "__init__.py": f'"""The {tool["id"]} MCP server."""\n',
        pkg / "server.py": render_server(tool),
        pkg / "__main__.py": render_main(tool),
        pkg / "test_server.py": render_test(tool),
    }
    clash = [p for p in files if p.exists()]
    if clash and not force:
        raise FileExistsError("would overwrite " + ", ".join(str(p) for p in clash) +
                              " (pass --force to replace them)")
    written = []
    init = base / "__init__.py"
    if not init.exists():
        files[init] = '"""MCP tool servers for this project."""\n'
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written
